def _ranking_models_available() -> bool:
    """True if trained ML ranking models exist (xgboost.joblib or random_forest.joblib)."""
    models_dir = ROOT / "data/ranking/models"
    return models_dir.is_dir() and any(models_dir.glob("*.joblib"))


def _ranking_datasets_available() -> bool:
    """True if ranking dataset JSONL files exist (unlabeled or pseudo-labeled)."""
    ds_dir = ROOT / "data/ranking/datasets"
    return ds_dir.is_dir() and any(ds_dir.glob("*.jsonl"))


def _matching_v3_report_available() -> bool:
    """True if any v3 normalized matching report exists on disk."""
    v3_dir = ROOT / "docs/reports/matching/v3"
    return v3_dir.is_dir() and any(v3_dir.glob("*matching_report_v3_normalized.json"))


def _decision_cards_v3_available() -> bool:
    """True if the normalized v3 decision cards artifact exists on disk."""
    return (ROOT / "docs/reports/matching/v3/decision_cards_v3_normalized.json").exists()


def _cv_fixtures_available() -> bool:
    """True if canonical CV fixture files used by resolver tests exist on disk."""
    return (ROOT / "data/raw_cv/pdf/Image_73.pdf").exists()


def _annotation_sample_available() -> bool:
    """True if the human annotation sample CSV exists."""
    return (ROOT / "data/ranking/annotations/annotation_sample.csv").exists()


def _grounded_profiles_available() -> bool:
    """True if the specific legacy grounded profile used as test fixture exists."""
    return (
        ROOT / "data/profile_builder_module2_v2_grounded_all/profiles/grounded_profiles/docx_Aziz_resumer.json"
    ).exists()


def _ml_experiment_reports_available() -> bool:
    """True if ML experiment interpretation reports exist (generated by training pipeline)."""
    return (ROOT / "docs/reports/ml/ml_experiment_interpretation.json").exists()


def _copilot_reports_available() -> bool:
    """True if copilot evaluation reports exist on disk."""
    return (ROOT / "docs/reports/copilot/copilot_evaluation.json").exists()


