    ranking_models_available = _ranking_models_available()
    ranking_datasets_available = _ranking_datasets_available()
    matching_v3_available = _matching_v3_report_available()
    decision_cards_v3_available = _decision_cards_v3_available()
    cv_fixtures_available = _cv_fixtures_available()
    annotation_sample_available = _annotation_sample_available()
    grounded_profiles_available = _grounded_profiles_available()
    ml_experiment_reports_available = _ml_experiment_reports_available()
    copilot_reports_available = _copilot_reports_available()

    artifact_skip = pytest.mark.skip(reason=_ARTIFACT_SKIP_REASON)
    report_skip = pytest.mark.skip(reason=_REPORT_SKIP_REASON)
    ml_pipeline_skip = pytest.mark.skip(reason=_ML_PIPELINE_SKIP_REASON)
    cv_fixtures_skip = pytest.mark.skip(reason=_CV_FIXTURES_SKIP_REASON)
