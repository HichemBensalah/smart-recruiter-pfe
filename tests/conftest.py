    grounded_profiles_skip = pytest.mark.skip(reason=_GROUNDED_PROFILES_SKIP_REASON)
    ml_reports_skip = pytest.mark.skip(reason=_ML_REPORTS_SKIP_REASON)
    copilot_reports_skip = pytest.mark.skip(reason=_COPILOT_REPORTS_SKIP_REASON)

    for item in items:
        nid = item.nodeid.replace("\\", "/")

        if not artifact_available and nid in _ARTIFACT_DEPENDENT_NODEIDS:
            item.add_marker(artifact_skip)
        elif not demo_available and nid in _DEMO_REPORT_NODEIDS:
            item.add_marker(report_skip)
        elif not neo4j_available and nid in _NEO4J_REPORT_NODEIDS:
            item.add_marker(report_skip)
        elif not ranking_models_available and nid in _RANKING_MODELS_NODEIDS:
            item.add_marker(ml_pipeline_skip)
        elif not ranking_datasets_available and nid in _RANKING_DATASETS_NODEIDS:
            item.add_marker(ml_pipeline_skip)
        elif not matching_v3_available and nid in _MATCHING_V3_REPORT_NODEIDS:
            item.add_marker(matching_report_skip)
        elif not decision_cards_v3_available and nid in _DECISION_CARDS_V3_NODEIDS:
            item.add_marker(decision_cards_skip)
        elif not cv_fixtures_available and nid in _CV_FIXTURES_NODEIDS:
            item.add_marker(cv_fixtures_skip)
